import AppKit
import ImageIO
import UniformTypeIdentifiers
import CryptoKit

/// Captures only the image inputs, then decodes them away from the UI thread.
public enum ClipboardImageReader {
    public enum Input: Sendable {
        case file(URL)
        case data(Data)
    }
    public struct DecodedImage: Sendable {
        public let png: Data
        public let fingerprint: String
    }

    /// Our own copy action must not become a new import after file copies are enabled.
    public static let ownCopyType = NSPasteboard.PasteboardType("com.baiyuff001.imageline.own-copy")
    public static let maxBytes = 64 * 1024 * 1024
    private static let maxPixels = 80_000_000
    private static let legacyFiles = NSPasteboard.PasteboardType("NSFilenamesPboardType")
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        ownCopyType,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let textTypes: Set<NSPasteboard.PasteboardType> = [
        .string, .rtf, .rtfd, .html, .tabularText,
    ]

    @MainActor
    public static func snapshot(_ pasteboard: NSPasteboard) -> [Input] {
        guard let items = pasteboard.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ privateTypes.isDisjoint(with: $0.types) }) else { return [] }
        // File references take precedence over icons, text and preview images.
        // A copied PDF or folder may advertise PNG data too; never hang its icon.
        let hasFiles = items.contains { $0.types.contains(.fileURL) || $0.types.contains(legacyFiles) }
            || (pasteboard.types ?? []).contains(legacyFiles)
        if hasFiles {
            var urls = items.compactMap { item -> URL? in
                guard let raw = item.string(forType: .fileURL),
                      let url = URL(string: raw), url.isFileURL else { return nil }
                return url
            }
            // macOS synthesizes legacy paths even from malformed non-file
            // URLs. Only use that fallback when no modern URL was supplied.
            if !items.contains(where: { $0.types.contains(.fileURL) }),
               let paths = pasteboard.propertyList(forType: legacyFiles) as? [String] {
                urls += paths.map { URL(fileURLWithPath: $0) }
            }
            var seen = Set<URL>()
            return urls.compactMap { url in
                let resolved = url.standardizedFileURL.resolvingSymlinksInPath()
                return seen.insert(resolved).inserted ? .file(resolved) : nil
            }
        }
        var remainingBytes = maxBytes
        return items.compactMap { item in
            // Office text often includes an image preview and RTF/HTML rather
            // than public.utf8-plain-text. These are still text copies.
            guard !item.types.contains(where: {
                textTypes.contains($0) || UTType($0.rawValue)?.conforms(to: .text) == true
            }) else { return nil }
            let imageTypes = item.types.filter { UTType($0.rawValue)?.conforms(to: .image) == true }
            let preferred = [NSPasteboard.PasteboardType.png, .tiff] + imageTypes
            for type in preferred where item.types.contains(type) {
                if let data = item.data(forType: type), !data.isEmpty, data.count <= remainingBytes {
                    remainingBytes -= data.count
                    return .data(data)
                }
            }
            return nil
        }
    }

    /// Makes a standalone PNG; the source file is never edited, moved or deleted.
    public static func png(from input: Input) -> Data? {
        decode(input)?.png
    }

    public static func decode(_ input: Input) -> DecodedImage? {
        let data: Data
        switch input {
        case .data(let bytes): data = bytes
        case .file(let url):
            guard url.isFileURL,
                  let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey]),
                  values.isRegularFile == true,
                  let size = values.fileSize, size > 0, size <= maxBytes,
                  let bytes = try? Data(contentsOf: url, options: .mappedIfSafe) else { return nil }
            data = bytes
        }
        guard !data.isEmpty, data.count <= maxBytes,
              let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let identifier = CGImageSourceGetType(source),
              UTType(identifier as String)?.conforms(to: .image) == true,
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, width <= maxPixels / height else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: max(width, height),
            kCGImageSourceShouldCacheImmediately: true,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary),
              let fingerprint = pixelFingerprint(image) else { return nil }
        let orientation = properties[kCGImagePropertyOrientation] as? Int ?? 1
        if identifier as String == UTType.png.identifier && orientation == 1 {
            return DecodedImage(png: data, fingerprint: fingerprint)
        }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination), output.length <= maxBytes else { return nil }
        return DecodedImage(png: output as Data, fingerprint: fingerprint)
    }

    /// PNG/ICC metadata can contain a new timestamp on every conversion.
    /// Hash fixed-layout sRGB pixels, dimensions and alpha, never encoded bytes.
    private static func pixelFingerprint(_ image: CGImage) -> String? {
        guard let context = CGContext(data: nil, width: image.width, height: image.height,
            bitsPerComponent: 8, bytesPerRow: image.width * 4,
            space: CGColorSpace(name: CGColorSpace.sRGB)!,
            bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue),
              let pixels = context.data else { return nil }
        context.draw(image, in: CGRect(x: 0, y: 0, width: image.width, height: image.height))
        var hash = SHA256()
        hash.update(data: Data("\(image.width)x\(image.height):sRGB-RGBA8:".utf8))
        hash.update(bufferPointer: UnsafeRawBufferPointer(start: pixels, count: image.width * image.height * 4))
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }
}
