import AppKit

/// Hangs images copied to the clipboard: a screenshot taken with Control
/// held, "Copy Image" in a browser, or an image file copied in Finder.
/// The pasteboard has no change notification, so it is polled.
@MainActor
final class ClipboardWatcher {
    private let onImage: (URL) -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// Set by the line when it copies a photo itself, so that copy is not hung again.
    static var ownChangeCount = -1

    private static let enabledKey = "clipboardEnabled"
    private static let textKey = "clipboardTextEnabled"
    private static let offeredKey = "clipboardOffered"

    /// Off until the user turns it on: reading the clipboard is their call.
    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    /// Copied text hangs too, as a little note card.
    static var textEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: textKey) }
        set { UserDefaults.standard.set(newValue, forKey: textKey) }
    }

    /// Whether we already asked, so the offer appears only once.
    static var wasOffered: Bool {
        get { UserDefaults.standard.bool(forKey: offeredKey) }
        set { UserDefaults.standard.set(newValue, forKey: offeredKey) }
    }

    private static let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "tif", "tiff", "gif", "webp", "bmp"]
    /// Marked by password managers and similar apps as not for history tools.
    private static let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                       "org.nspasteboard.AutoGeneratedType"].map { NSPasteboard.PasteboardType($0) }

    init(onImage: @escaping (URL) -> Void) {
        self.onImage = onImage
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard pb.changeCount != Self.ownChangeCount else { return }
        let types = pb.types ?? []
        if types.contains(where: Self.privateTypes.contains) { return }

        // Files copied in Finder: hang the image files themselves. Finder also
        // puts the file's icon on the clipboard, which must not be hung.
        if types.contains(.fileURL) {
            guard Self.isEnabled else { return }
            let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
            for url in urls where Self.imageExtensions.contains(url.pathExtension.lowercased()) {
                onImage(url)
            }
            return
        }

        if Self.isEnabled, let data = pngData(from: pb) {
            save(data, ext: "png")
        } else if Self.textEnabled, let text = pb.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            save(Data(text.utf8), ext: "txt")
        }
    }

    private func save(_ data: Data, ext: String) {
        try? FileManager.default.createDirectory(at: Inbox.folder, withIntermediateDirectories: true)
        var url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()).\(ext)")
        var n = 2
        while FileManager.default.fileExists(atPath: url.path) {
            url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()) \(n).\(ext)")
            n += 1
        }
        do {
            try data.write(to: url, options: .atomic)
            onImage(url)
        } catch {
            log.error("Could not save clipboard \(ext, privacy: .public): \(error.localizedDescription, privacy: .public)")
        }
    }

    private func pngData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private static func stamp() -> String {
        let f = DateFormatter()
        f.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        return f.string(from: Date())
    }
}
