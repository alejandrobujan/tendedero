import AppKit

/// Hangs images and text snippets copied to the clipboard.
/// Each one is saved in Tendedero's own folder, so on the line it behaves
/// like any screenshot.
///
/// Images and text can be toggled independently from the menu bar.
/// The pasteboard has no change notification, so its change count is checked
/// twice a second.
@MainActor
final class ClipboardWatcher {
    private let onItem: (URL) -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// The last image saved.
    private var lastImage: (png: Data, url: URL)?
    /// The last text saved.
    private var lastText: (content: String, url: URL)?

    private static let imageEnabledKey = "clipboardEnabled"
    private static let textEnabledKey = "clipboardTextEnabled"

    static var isImageEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: imageEnabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: imageEnabledKey) }
    }

    static var isTextEnabled: Bool {
        get {
            if UserDefaults.standard.object(forKey: textEnabledKey) == nil {
                return true
            }
            return UserDefaults.standard.bool(forKey: textEnabledKey)
        }
        set { UserDefaults.standard.set(newValue, forKey: textEnabledKey) }
    }

    /// Backwards compatibility for existing code.
    static var isEnabled: Bool {
        get { isImageEnabled }
        set { isImageEnabled = newValue }
    }

    /// Password managers and similar apps mark private or temporary copies,
    /// following nspasteboard.org.
    private static let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Copies that carry a picture but are not one. Text from a spreadsheet
    /// or a document also comes as an image of itself. A file copied in
    /// Finder brings its icon, and a photo copied from the line brings its
    /// file.
    private static let ignoredImageTypes: Set<NSPasteboard.PasteboardType> = [
        .string, .fileURL,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Anything bigger is not a screenshot.
    private static let maxBytes = 64 * 1024 * 1024
    nonisolated private static let maxPixels = 80_000_000
    private static let maxTextBytes = 1024 * 1024

    init(onItem: @escaping (URL) -> Void) {
        self.onItem = onItem
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard let items = pb.pasteboardItems, !items.isEmpty else { return }

        // Skip sensitive / password-manager clipboard data.
        if items.contains(where: { !Self.sensitiveTypes.isDisjoint(with: $0.types) }) {
            return
        }

        // 1. Copied image
        if Self.isImageEnabled,
           items.allSatisfy({ Self.ignoredImageTypes.isDisjoint(with: $0.types) }),
           let type = pb.availableType(from: [.png, .tiff]),
           let data = pb.data(forType: type), data.count <= Self.maxBytes,
           pb.changeCount == count {
            DispatchQueue.global(qos: .userInitiated).async { [weak self] in
                let png = ClipboardWatcher.png(from: data, type: type)
                DispatchQueue.main.async {
                    guard let png, NSPasteboard.general.changeCount == count else { return }
                    self?.saveImage(png)
                }
            }
            return
        }

        // 2. Copied text snippet
        if Self.isTextEnabled,
           items.allSatisfy({ !$0.types.contains(.fileURL) }),
           let string = pb.string(forType: .string) {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty, string.utf8.count <= Self.maxTextBytes else { return }
            saveText(string)
        }
    }

    /// PNG bytes are kept as they are; TIFF becomes PNG. Either way the image
    /// must decode and have a sane size.
    nonisolated private static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard let rep = NSBitmapImageRep(data: data),
              rep.pixelsWide > 0, rep.pixelsHigh > 0,
              rep.pixelsWide <= maxPixels / rep.pixelsHigh else { return nil }
        return type == .png ? data : rep.representation(using: .png, properties: [:])
    }

    private func saveImage(_ png: Data) {
        if let lastImage, lastImage.png == png, FileManager.default.fileExists(atPath: lastImage.url.path) { return }
        let fm = FileManager.default
        var url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()).png")
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()) \(n).png")
            n += 1
        }
        do {
            try fm.createDirectory(at: Inbox.folder, withIntermediateDirectories: true)
            try png.write(to: url, options: .atomic)
            // What people copy can be private: only they can read it.
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            lastImage = (png, url)
            onItem(url)
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save a copied image: \(error.localizedDescription, privacy: .public)")
        }
    }

    private func saveText(_ text: String) {
        if let lastText, lastText.content == text, FileManager.default.fileExists(atPath: lastText.url.path) { return }
        let fm = FileManager.default
        var url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()).txt")
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()) \(n).txt")
            n += 1
        }
        do {
            try fm.createDirectory(at: Inbox.folder, withIntermediateDirectories: true)
            guard let data = text.data(using: .utf8) else { return }
            try data.write(to: url, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            lastText = (text, url)
            onItem(url)
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save copied text: \(error.localizedDescription, privacy: .public)")
        }
    }

    private static func stamp() -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        return f.string(from: Date())
    }
}
